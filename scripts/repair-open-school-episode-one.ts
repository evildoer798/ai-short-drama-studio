const episode = await prisma.scriptEpisode.findUniqueOrThrow({
  where: {
    projectId_episodeNumber: {
      projectId: PROJECT_ID,
      episodeNumber: EPISODE_NUMBER,
    },
  },
  select: { id: true, content: true, locked: true },
})
if (!episode.locked) throw new Error('Episode 1 is not locked')

const missing = extractRequiredStoryboardDialogueLines(episode.content)
  .filter((dialogue) => storyboardDialogueMissing(shots, dialogue))
if (missing.length > 0) {
  throw new Error(`Manual storyboard dialogue coverage failed: ${JSON.stringify(missing)}`)
}

const existing = await prisma.storyboard.findMany({
  where: { projectId: PROJECT_ID, episodeId: episode.id, generatedByAI: true },
  orderBy: { episodeSceneNumber: 'asc' },
  include: { _count: { select: { videos: true } } },
})
if (existing.length !== items.length) {
  throw new Error(`Expected ${items.length} existing storyboards, found ${existing.length}`)
}

await prisma.$transaction(async (tx) => {
  for (let index = 0; index < items.length; index++) {
    const item = items[index]
    await tx.storyboard.update({
      where: { id: existing[index].id },
      data: {
        episodeSceneNumber: index + 1,
        title: item.title,
        notes: item.notes || null,
        imagePrompt: item.imagePrompt || null,
        videoPrompt: item.videoPrompt,
        duration: item.duration,
        aspectRatio: item.aspectRatio,
        generateAudio: true,
        continuityIn: item.continuityIn,
        continuityOut: item.continuityOut,
      },
    })
  }

  const latestTask = await tx.generationTask.findFirst({
    where: { projectId: PROJECT_ID, type: 'storyboard_generation' },
    orderBy: { createdAt: 'desc' },
  })
  if (latestTask) {
    const payload = latestTask.payload && typeof latestTask.payload === 'object' && !Array.isArray(latestTask.payload)
      ? { ...(latestTask.payload as Prisma.JsonObject) }
      : {}
    const rawProgress = payload.storyboardProgress
    const progress = rawProgress && typeof rawProgress === 'object' && !Array.isArray(rawProgress)
      ? { ...(rawProgress as Prisma.JsonObject) }
      : {}
    delete progress.warning
    delete progress.suggestions
    progress.remainingIssues = 0
    progress.fatalIssues = 0
    const modifiedShotCount = Math.max(
      Number(progress.modifiedShots || 0),
      Number(payload.modifiedShots || 0),
      items.length,
    )
    progress.modifiedShots = modifiedShotCount
    payload.reviewWarnings = []
    payload.modifiedShots = modifiedShotCount
    payload.storyboardProgress = progress
    payload.pipelineVersion = 'cine-lock-emotional-storyboards-v12-semantic-repair'
    payload.manualRepair = {
      episodeNumber: EPISODE_NUMBER,
      storyboardCount: items.length,
      totalSeconds: items.reduce((total, item) => total + item.duration, 0),
      reason: 'Applied locked-script review findings with dialogue-safe adaptation',
      repairedAt: new Date().toISOString(),
    }
    await tx.generationTask.update({
      where: { id: latestTask.id },
      data: { payload: payload as Prisma.InputJsonObject },
    })
  }
}, { timeout: 30_000 })

for (const storyboard of existing) {
  await syncStoryboardAssetLinks(storyboard.id)
}

